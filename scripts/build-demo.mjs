import { mkdir, readFile, writeFile, copyFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { sampleAuditSource } = require('../web/app.js');
const root = new URL('../', import.meta.url);
const source = await readFile(new URL('web/index.html', root), 'utf8');
assert.ok(source.includes('<html lang="en">'), 'Expected the local app HTML root');
const sample = JSON.parse(await readFile(new URL('demo/sample-audit.json', root), 'utf8'));
assert.equal(sample.sample.sourceSha256, createHash('sha256').update(sampleAuditSource).digest('hex'), 'Regenerate the sample with the running Unison server');
assert.equal(sample.checks.length, 7);
const html = source.replace('<html lang="en">', '<html lang="en" data-hosting="static-demo">');
assert.ok(html.includes('href="./styles.css"') && html.includes('src="./app.js"'), 'Demo assets must use relative paths');
await mkdir(new URL('dist/', root), { recursive: true });
await writeFile(new URL('dist/index.html', root), html);
for (const file of ['styles.css', 'app.js']) await copyFile(new URL(`web/${file}`, root), new URL(`dist/${file}`, root));
await copyFile(new URL('demo/sample-audit.json', root), new URL('dist/sample-audit.json', root));
await writeFile(new URL('dist/.nojekyll', root), '');
console.log('GitHub Pages demo built in dist/: relative assets, sample provenance verified.');
