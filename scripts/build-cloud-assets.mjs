import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const entries = [['html', 'index.html'], ['css', 'styles.css'], ['javascript', 'app.js']];
const terms = [];
for (const [term, file] of entries) {
  const source = await readFile(new URL(`web/${file}`, root), 'utf8');
  if (term === 'html' && source.includes('data-hosting="static-demo"')) throw new Error('Cloud must serve the live Unison app');
  terms.push(`summit.assets.${term} : Text\nsummit.assets.${term} = ${JSON.stringify(source)}\n`);
}
await writeFile(new URL('src/cloud-assets.u', root), '-- Generated by node scripts/build-cloud-assets.mjs. Do not edit by hand.\n' + terms.join('\n'));
console.log('Embedded browser assets as Unison Text definitions for Cloud deployment.');
